// -----------------------------------------------------------------------------
// Fluid type scale generator.
//
// Why this exists: the design system defines a fixed desktop size per text
// style (e.g. Display/2XL = 72px), but the user wants sizes that SCALE
// smoothly between a minimum (small screens) and maximum (large screens)
// instead of jumping at breakpoints. This script computes the CSS clamp()
// formula for each style once; the OUTPUT is pasted into
// src/app/globals.css as static values (clamp() needs no JavaScript at
// runtime — the math only needs to happen once, here).
//
// To change the scale: edit SCALE below and re-run `node scripts/generate-fluid-type.mjs`,
// then paste the printed block into globals.css.
// -----------------------------------------------------------------------------

const MIN_VIEWPORT = 390; // mobile reference width (matches the Figma mobile frame)
const MAX_VIEWPORT = 1920; // desktop reference width (matches the Figma desktop frame)
const ROOT_FONT_SIZE = 16; // browser default, for px -> rem conversion

// name: [minPx, maxPx] — fluid styles only. Label/Caption/Code are deliberately
// fixed-size (see globals.css) because shrinking small UI/mono text hurts
// readability more than it helps visual scaling.
const SCALE = {
  "display-2xl": [40, 72],
  "display-xl": [36, 60],
  "display-lg": [32, 48],
  "heading-1": [28, 40],
  "heading-2": [24, 32],
  "heading-3": [22, 28],
  "heading-4": [20, 24],
  "heading-5": [18, 20],
  "body-lg": [16, 18],
  "body-md": [15, 16],
  "body-sm": [13, 14],
};

function toRem(px) {
  return px / ROOT_FONT_SIZE;
}

function clampFor(minPx, maxPx) {
  const slope = (maxPx - minPx) / (MAX_VIEWPORT - MIN_VIEWPORT);
  const intersectionPx = minPx - slope * MIN_VIEWPORT;
  const slopeVw = (slope * 100).toFixed(4);
  const intersectionRem = toRem(intersectionPx).toFixed(4);
  const minRem = toRem(minPx).toFixed(4);
  const maxRem = toRem(maxPx).toFixed(4);
  return `clamp(${minRem}rem, ${intersectionRem}rem + ${slopeVw}vw, ${maxRem}rem)`;
}

console.log(`/* Generated by scripts/generate-fluid-type.mjs — do not hand-edit these values. */`);
for (const [name, [minPx, maxPx]] of Object.entries(SCALE)) {
  console.log(`--font-size-${name}: ${clampFor(minPx, maxPx)}; /* ${minPx}px -> ${maxPx}px */`);
}
